public class CJ07_TiposPrimitivos {
    public static void main(String[] args) {
       
        System.out.println("""
                            =========================================
                             \t   TIPOS DE DATOS PRIMITIVOS
                             =========================================""");

       
        byte edad = 38;                     
        short anio = 2026;                 
        int cedula = 16029567;              
        long telefono = 4242814455L;        

      
        float promedio = 19.75f;            
        double saldo = 1540.8599;           

      
        char inicial = 'D';                
        boolean esDesarrollador = true;      
        String mensaje = """
                ╔═══════════════════════════════════════╗
                ║  LOS 8 TIPOS PRIMITIVOS EN JAVA       ║
                ╚═══════════════════════════════════════╝
                """;
        System.out.print(mensaje);
        System.out.println("byte 8 bits (-128 a 127)    : " + edad);
        System.out.println("short 16 bits (-32,768 a 32,767) : " + anio);
        System.out.println("int 32 bits (-2,147,483,648 a 2,147,483,647) : " + cedula);
        System.out.println("long 64 bits : " + telefono);
        System.out.println("float 32 bits : " + promedio);
        System.out.println("double 64 bits : " + saldo);
        System.out.println("char 16 bits : " + inicial);
        System.out.println("boolean   : " + esDesarrollador);
    }
}
